<script>
$(document).ready(function () {
    let selectedPmId = null;

    // ── Payment method card selection
    $('#pm-grid').on('click', '.pm-card', function () {
        $('#pm-grid .pm-card').removeClass('selected');
        $(this).addClass('selected');

        selectedPmId = $(this).data('pm-id');
        const name         = $(this).data('pm-name');
        const account      = $(this).data('pm-account') || '';
        const holder       = $(this).data('pm-holder') || '';
        const instructions = $(this).data('pm-instructions') || '';
        const color        = $(this).find('.pm-icon-wrap').css('background-color');

        // Update info bar
        $('#pm-info-name').text(name);
        $('#pm-info-account').text(account ? '🔢 ' + account : '');
        $('#pm-info-holder').text(holder ? '👤 ' + holder : '');
        $('#pm-info-instructions').text(instructions);
        $('#pm-info-bar').show();

        // Apply border color
        $(this).css('border-color', $(this).find('.pm-icon-wrap').css('background-color'));

        // Enable submit button
        $('#btn-submit-payment').prop('disabled', false).html('<i class="far fa-credit-card mr-2"></i> Submit Payment via ' + name);
        $('#pm-hint').hide();

        // Sync to modal
        $('#modal-pm-id').val(selectedPmId);
        $('#modal-pm-name').text(name);
        $('#modal-pm-acct').text(account ? '— Acct: ' + account + (holder ? ' / ' + holder : '') : '');
    });

    // ── Proof image preview
    $('#proof_image').on('change', function () {
        if (this.files && this.files[0] && this.files[0].type.startsWith('image/')) {
            const r = new FileReader();
            r.onload = e => { $('#proof-preview').attr('src', e.target.result); $('#proof-preview-wrap').show(); };
            r.readAsDataURL(this.files[0]);
        } else {
            $('#proof-preview-wrap').hide();
        }
    });

    // ── Prevent modal opening without a method selected
    $('#btn-submit-payment').on('click', function (e) {
        if (!selectedPmId) {
            e.preventDefault(); e.stopPropagation();
            alert('Please select a payment method first.');
        }
    });
});
</script>
